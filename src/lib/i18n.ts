export function getTranslation(language: Language, key: string): string {
  const keys = key.split('.');
  let current: any = translations[language];

  for (const k of keys) {
    current = current?.[k];
    if (!current) break;
  }

  return current || key;
}

export function getSupportedLanguages() {
  return [
    { code: 'en', name: 'English' },
    { code: 'ta', name: 'தமிழ்' },
  ];
}
